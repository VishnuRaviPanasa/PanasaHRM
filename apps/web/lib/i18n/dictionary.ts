/**
 * The translation resources. English is the source; Arabic is typed FROM it.
 *
 * WHY A DICTIONARY IN THE REPOSITORY AND NOT A LIBRARY. `next-intl` and friends earn their keep
 * on locale-segmented ROUTING and server-component message loading. This application is 19
 * client components behind one shell with no locale in the URL, so almost none of that applies -
 * what is actually needed is a keyed lookup, a direction, and locale-aware date and number
 * formatting, the last of which the platform already provides through `Intl`. A dependency whose
 * useful surface here is one function would also need recording under the supply-chain rule in
 * CLAUDE.md, for no capability this file lacks.
 *
 * THE TYPE IS THE MISSING-KEY TEST. `Dictionary` is derived from the English object, and `ar`
 * is annotated with it - so omitting a key, or inventing one that English does not have, is a
 * COMPILE error rather than a string like "attendance.title" appearing on screen in production.
 * That is the strongest form the requirement "no missing translation-key errors" can take: it
 * cannot reach a browser to be caught by a test.
 *
 * ARABIC REVIEW IS STILL OUTSTANDING. These are careful translations, not reviewed ones. HR
 * vocabulary is domain vocabulary - "قسيمة الراتب" for a payslip, "المهمة الفرعية" for a
 * sub-task - and a native speaker in an HR context should read this file before the Arabic is
 * shown to anybody outside the team. Recorded in the handover rather than left implicit.
 */

export const LOCALES = ['en', 'ar'] as const;
export type Locale = (typeof LOCALES)[number];

/**
 * The cookie the locale lives in, and its validator.
 *
 * THESE LIVE HERE, IN A MODULE WITH NO 'use client', BECAUSE THE SERVER CALLS THEM.
 *
 * They were first exported from `index.tsx`, which is a client module - and the root layout, a
 * SERVER component, called `isLocale()` on the cookie. That compiles perfectly and then fails at
 * request time with "Attempted to call isLocale() from the server but isLocale is on the client",
 * a 500 on every page. `next build` cannot catch it, which is why a build passing is not evidence
 * that a server/client boundary is right.
 */
export const LOCALE_COOKIE = 'hrm_locale';

export const isLocale = (v: unknown): v is Locale =>
  typeof v === 'string' && (LOCALES as readonly string[]).includes(v);

